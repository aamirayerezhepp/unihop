const VERIFIED = new Set([
  'Harvard University','Princeton University','Columbia University','Yale University','Cornell University','Johns Hopkins University',
  'Caltech','Duke University','University of Chicago','Northwestern University','Stanford University','University of Pennsylvania',
  'Brown University','New York University','MIT','UNC Chapel Hill','Purdue University','University of Michigan',
  'KAIST','University of Hong Kong'
]);
const isVerified = (name, type) => VERIFIED.has(name) || type === 'ucas' || type === 'ucasE';

/* Catalog rows as objects, with the next deadline date filled in. */
export const catalogItems = () => CATALOG.map(([n, c, mmdd, type, url, alt]) =>
  ({n, c, mmdd, type, url, alt, date:nextDate(mmdd), approx:!isVerified(n, type)}));

export const findInCatalog = name => {
  const row = CATALOG.find(r => r[0] === name);
  if (!row) return null;
  const [n, c, mmdd, type, url, alt] = row;
  return {n, c, mmdd, type, url, alt, date:nextDate(mmdd), approx:!isVerified(n, type)};
};
