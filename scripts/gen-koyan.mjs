// Builds src/data/koyanImages.js: the mascot PNGs as base64 data URIs, so the site needs no image folder.
// Run after changing a picture in src/assets/koyan: node scripts/gen-koyan.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src', 'assets', 'koyan');
const lines = readdirSync(dir).filter(f => /^koyan-[a-z]+\.png$/.test(f)).sort().map(f => {
  const pose = f.slice(6, -4);
  return `  ${pose}: 'data:image/png;base64,${readFileSync(join(dir, f)).toString('base64')}'`;
});
writeFileSync(join(root, 'src', 'data', 'koyanImages.js'),
  `/* Generated by scripts/gen-koyan.mjs from src/assets/koyan — do not edit by hand. */\nexport const KOYAN_IMG = {\n${lines.join(',\n')}\n};\n`);
console.log(`koyanImages.js: ${lines.length} poses`);
